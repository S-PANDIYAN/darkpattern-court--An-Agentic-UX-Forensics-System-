"""Court record generators: self-contained HTML evidence report and a printable PDF of evidence cards."""
from __future__ import annotations
import html
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Image as RLImage, Table, TableStyle, PageBreak, KeepTogether

VCOL = {"GUILTY": "#dc2626", "LIKELY": "#d97706", "INSUFFICIENT EVIDENCE": "#6b7280"}
e = html.escape


def write_html(case: dict, out: Path):
    v = case["verdict"]
    parts = [f"""<!doctype html><html><head><meta charset="utf-8"><title>DarkPattern Court — Case {e(case['id'])}</title>
<style>body{{font-family:system-ui,Segoe UI,Arial;margin:0;background:#f3f4f6;color:#111827}}main{{max-width:1000px;margin:auto;padding:24px}}
.hdr{{background:#111827;color:#fff;padding:24px;border-radius:12px}}.v{{font-size:28px;font-weight:800}}.card{{background:#fff;border-radius:12px;padding:18px;margin:16px 0;box-shadow:0 1px 3px #0002}}
.badge{{display:inline-block;padding:3px 10px;border-radius:99px;color:#fff;font-size:12px;font-weight:700}}img{{max-width:100%;border:1px solid #e5e7eb;border-radius:8px}}
.step{{border-left:3px solid #6366f1;padding:4px 12px;margin:8px 0}}.obs{{color:#b91c1c;font-size:14px}}small{{color:#6b7280}}blockquote{{margin:6px 0;padding:6px 12px;background:#f9fafb;border-left:3px solid #9ca3af;font-size:13px}}</style></head><body><main>
<div class="hdr"><div>⚖️ DarkPattern Court — Case {e(case['id'])}</div><div class="v">{e(v['label'])}: {e(v['summary'])}</div>
<div>Defendant interface: {e(case['url'])}<br>Manipulation score {v['manipulation_score']}/100 · Grade {v['grade']} · {len(case['findings'])} exhibits</div></div>"""]
    parts.append("<div class='card'><h2>Testimony — simulated user journeys</h2>")
    for j in case["journeys"]:
        parts.append(f"<h3>{e(j['label'])} — {'✅ reached' if j['reached'] else '❌ not reached'} in {j['clicks']} clicks</h3>")
        for s in j["steps"]:
            obs = "".join(f"<div class='obs'>⚠ {e(o)}</div>" for o in s["observations"])
            parts.append(f"<div class='step'><b>Step {s['step']}:</b> {e(s['testimony'])}{obs}</div>")
    parts.append("</div>")
    for c in case["charges"]:
        parts.append(f"<div class='card'><span class='badge' style='background:{VCOL[c['verdict']]}'>{c['verdict']}</span> "
                     f"<b>{e(c['count_no'])}: {e(c['name'])}</b> <small>({e(c['category'] or '')} · India CCPA: {e(c['india_ccpa'] or '-')} · confidence {c['confidence']:.0%})</small>"
                     f"<p>{e(c['charge'] or '')}</p>")
        for x in c["exhibits"]:
            parts.append(f"<h4>Exhibit {e(x.get('id',''))} <small>step {x.get('step')} · source: {e(x['source'])} · {x['confidence']:.0%}</small></h4><p>{e(x['description'])}</p><ul>"
                         + "".join(f"<li>{e(ev)}</li>" for ev in x["evidence"]) + "</ul>")
            if x.get("exhibit"):
                parts.append(f"<img src='{e(x['exhibit'])}'>")
        parts.append("<h4>Legal & regulatory basis</h4>" + "".join(
            f"<blockquote><b>{e(a['source'])}</b><br>{e(a['excerpt'])}<br><a href='{e(a['url'])}'>{e(a['url'])}</a></blockquote>" for a in c["authorities"]))
        parts.append("</div>")
    parts.append("<p><small>Generated by DarkPattern Court. Automated findings are evidence for expert review, not legal advice.</small></p></main></body></html>")
    out.write_text("".join(parts), encoding="utf-8")


def write_pdf(case: dict, out: Path):
    base = out.parent
    ss = getSampleStyleSheet()
    small = ParagraphStyle("small", parent=ss["Normal"], fontSize=8.5, leading=11, textColor=colors.HexColor("#374151"))
    body = ParagraphStyle("b", parent=ss["Normal"], fontSize=10, leading=13)
    P = lambda t, s=body: Paragraph(e(str(t).replace("→", "->").replace("⚠", "!").replace("×", "x").replace("…", "...")), s)
    v = case["verdict"]
    doc = SimpleDocTemplate(str(out), pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=15 * mm, bottomMargin=15 * mm,
                            title=f"DarkPattern Court case {case['id']}")
    W = A4[0] - 30 * mm
    story = [Paragraph("DarkPattern Court — Evidence Record", ss["Title"]),
             P(f"Case {case['id']} · Interface under audit: {case['url']}"), Spacer(1, 6)]
    t = Table([[Paragraph(f"<b>VERDICT: {e(v['label'])}</b><br/>{e(v['summary'])}<br/>Manipulation score {v['manipulation_score']}/100 — grade {v['grade']}",
                          ParagraphStyle('v', parent=body, textColor=colors.white, fontSize=12, leading=16))]], colWidths=[W])
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#111827")), ("PADDING", (0, 0), (-1, -1), 10)]))
    story += [t, Spacer(1, 10), Paragraph("Charges", ss["Heading2"])]
    rows = [["Count", "Pattern", "Verdict", "Conf.", "Exhibits"]] + [[c["count_no"], c["name"], c["verdict"], f"{c['confidence']:.0%}", str(c["count"])] for c in case["charges"]]
    ct = Table(rows, colWidths=[W * .12, W * .45, W * .2, W * .1, W * .13])
    ct.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), .3, colors.grey), ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e5e7eb")), ("FONTSIZE", (0, 0), (-1, -1), 9)]))
    story += [ct, Spacer(1, 8), Paragraph("Testimony", ss["Heading2"])]
    for j in case["journeys"]:
        story.append(Paragraph(f"<b>{e(j['label'])}</b> — {'reached' if j['reached'] else 'NOT reached'} in {j['clicks']} clicks", body))
        for s in j["steps"]:
            story.append(P(f"Step {s['step']}: {s['testimony']}", small))
            for o in s["observations"]:
                story.append(Paragraph(f"&nbsp;&nbsp;! {e(o.replace('→', '->').replace('×', 'x'))}", ParagraphStyle('o', parent=small, textColor=colors.HexColor('#b91c1c'))))
        story.append(Spacer(1, 6))
    story.append(PageBreak())
    story.append(Paragraph("Evidence Cards", ss["Heading2"]))
    for c in case["charges"]:
        for x in c["exhibits"][:2]:
            card = [Paragraph(f"<b>{e(c['count_no'])} · {e(c['name'])} · <font color='{VCOL[c['verdict']]}'>{c['verdict']}</font></b>", body),
                    P(f"Exhibit {x.get('id')} — step {x.get('step')} — source {x['source']} — confidence {x['confidence']:.0%}", small),
                    P(x["description"], body)] + [P("• " + ev, small) for ev in x["evidence"]]
            if x.get("exhibit") and (base / x["exhibit"]).exists():
                from PIL import Image
                iw, ih = Image.open(base / x["exhibit"]).size
                w = min(W, iw * 0.6)
                h = w * ih / iw
                if h > 110 * mm:
                    h, w = 110 * mm, 110 * mm * iw / ih
                card.append(RLImage(str(base / x["exhibit"]), width=w, height=h))
            if c["authorities"]:
                a = c["authorities"][0]
                card.append(P(f"Authority: {a['source']} — {a['excerpt'][:300]}", small))
            tb = Table([[card]], colWidths=[W])
            tb.setStyle(TableStyle([("BOX", (0, 0), (-1, -1), .8, colors.HexColor(VCOL[c['verdict']])), ("PADDING", (0, 0), (-1, -1), 8)]))
            story += [KeepTogether(tb), Spacer(1, 8)]
    story.append(P("Automated findings are evidence for expert review, not legal advice.", small))
    doc.build(story)
